#!/usr/bin/env node
/**
 * Build the browser bundle.
 *
 * The DSH client loader expects a classic script envelope:
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => { ... } })
 *
 * `src/client.js` is the factory body; this script substitutes the stylesheet
 * placeholder and wraps it. No bundler, no dependencies, no build scripts
 * executed during plugin installation.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const manifest = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const css = await readFile(resolve(root, "src/style.css"), "utf8");
const source = await readFile(resolve(root, "src/client.js"), "utf8");
const helloFont = await readFile(resolve(root, "assets/fonts/dancing-script-latin.woff2"));

const FONT_PLACEHOLDER = "__DSLG_HELLO_FONT__";
if (!css.includes(FONT_PLACEHOLDER)) {
  throw new Error("src/style.css is missing the hello-font placeholder");
}
const cssWithFont = css.replace(
  FONT_PLACEHOLDER,
  `url("data:font/woff2;base64,${helloFont.toString("base64")}")`,
);

const PLACEHOLDER = '"__DSLG_CSS__"';
if (!source.includes(PLACEHOLDER)) {
  throw new Error("src/client.js is missing the CSS placeholder");
}

const body = source.replace(PLACEHOLDER, JSON.stringify(cssWithFont));
const banner = [
  "/*!",
  " * " + manifest.name + " v" + manifest.version,
  " * Apple-style liquid glass material for the DSH web client.",
  " * Generated by scripts/build.mjs — edit src/client.js and src/style.css.",
  " */",
].join("\n");

const output = [
  banner,
  "window.__ModuleLoader__.load({",
  "  id: " + JSON.stringify(manifest.name) + ",",
  "  factory: (require) => {",
  "    var module = { exports: {} };",
  "    var exports = module.exports;",
  "    Object.defineProperty(exports, Symbol.toStringTag, { value: \"Module\" });",
  body,
  "    return module.exports;",
  "  },",
  "});",
  "",
].join("\n");

await mkdir(resolve(root, "lib"), { recursive: true });
await writeFile(resolve(root, "lib/client.js"), output, "utf8");

const bytes = Buffer.byteLength(output, "utf8");
console.log(`built lib/client.js (${bytes.toLocaleString()} bytes)`);
